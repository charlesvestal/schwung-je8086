static int audio_ring_available(jp8000_shm_t *shm) {
    int avail = shm->ring_write - shm->ring_read;
    if (avail < 0) avail += AUDIO_RING_SIZE;
    return avail;
}

static int audio_ring_free(jp8000_shm_t *shm) {
    return AUDIO_RING_SIZE - 1 - audio_ring_available(shm);
}

static int gram_ring_available(const je_stage_t *st) {
    int avail = st->gram_write - st->gram_read;
    if (avail < 0) avail += JE_GRAM_RING_CAP * 2;
    return avail;
}

static int midi_fifo_available(jp8000_shm_t *shm) {
    int avail = shm->midi_write - shm->midi_read;
    if (avail < 0) avail += MIDI_FIFO_SIZE;
    return avail;
}

static int midi_fifo_free(jp8000_shm_t *shm) {
    return MIDI_FIFO_SIZE - 1 - midi_fifo_available(shm);
}

static int uc_write_ring_available(const je_stage_t *st) {
    int avail = st->uc_write - st->uc_read;
    if (avail < 0) avail += UC_WRITE_RING_CAP;
    return avail;
}

static void uc_write_ring_push(je_stage_t *st, int asic, uint32_t addr, uint8_t val,
                               uint32_t sample) {
    if (uc_write_ring_available(st) >= UC_WRITE_RING_CAP - 1) return; /* drop if full */
    int wi = st->uc_write;
    st->uc_ring[wi] = uc_write_t{ (uint8_t)asic, val, (uint16_t)addr, sample };
    SHM_STORE_FENCE();
    st->uc_write = (wi + 1) % UC_WRITE_RING_CAP;
}

/*
 * Scheduling policy of the DSP processes. The child is forked from whatever
 * thread called create_instance, and inherits its class: the SPI callback
 * (FIFO 70) on today's chain host, a FIFO 20 loader once schwung#303 lands,
 * SCHED_OTHER under plugin_drive run as `ableton`.
 *
 * Measured 2026-09-02 on the device at 1.15x with Move running: SCHED_OTHER
 * stages get preempted by MoveOriginal's main thread (~45-90% of a core) for
 * ~100 ms windows and underrun 4 runs in 6; at FIFO 20 the ring never leaves
 * the throttle, 6 runs in 6. FIFO 70 is worse than either: it is above Move's
 * `Link Main` (35) and starves Link Audio delivery — the "fork" entry in the
 * 2026-08-22 RT thread audit was this module.
 *
 * So: an inherited realtime priority is CLAMPED to JP8000_RT_PRIO, never
 * raised and never dropped to SCHED_OTHER. MoveOriginal runs as `ableton`
 * with RLIMIT_RTPRIO 0, so a process that leaves the realtime class cannot
 * come back; and the stages fork from this process later and inherit
 * whatever this leaves in place.
 */
#define JP8000_RT_PRIO 20
/* Experiment switch (not a setting): with this file present the stages leave
 * the realtime class entirely, so the in-host cost of SCHED_OTHER can be
 * measured against the FIFO 20 number above. Checked once per stage. */
#define JP8000_SCHED_OTHER_ARM_FILE "/data/UserData/schwung/jp8000_sched_other_on"
static void child_clamp_realtime(jp8000_shm_t *shm) {
    (void)shm;
#ifdef __linux__
    const int pol = sched_getscheduler(0);
    if (pol != SCHED_FIFO && pol != SCHED_RR) {
        vlog("[child] sched: inherited SCHED_OTHER, leaving it");
        return;
    }
    struct sched_param sp{};
    sched_getparam(0, &sp);
    if (access(JP8000_SCHED_OTHER_ARM_FILE, F_OK) == 0) {
        struct sched_param other{};
        const int rc = sched_setscheduler(0, SCHED_OTHER, &other);
        vlog("[child] sched: inherited FIFO %d -> SCHED_OTHER by arming file (rc=%d, now pol=%d)",
             sp.sched_priority, rc, sched_getscheduler(0));
        return;
    }
    if (sp.sched_priority <= JP8000_RT_PRIO) {
        vlog("[child] sched: inherited FIFO %d, leaving it", sp.sched_priority);
        return;
    }
    const int inherited = sp.sched_priority;
    sp.sched_priority = JP8000_RT_PRIO;
    const int rc = sched_setscheduler(0, SCHED_FIFO, &sp);
    sched_getparam(0, &sp);  /* verify: sched_setscheduler has failed silently on this device before */
    vlog("[child] sched: inherited FIFO %d -> FIFO %d (rc=%d, now %d)", inherited, JP8000_RT_PRIO, rc, sp.sched_priority);
#endif
}

/* Wait for a cross-process condition: spin briefly (the other side is one
 * sample away most of the time), then back off to usleep so an idle core is
 * not burned while the parent throttles on the audio ring.
 *
 * The back-off is exponential up to 250 us, and it has to be. Stage 0 fills
 * the audio ring in bursts (one block every 2.9 ms, at its throttle level);
 * stages 1/2 finish each burst in under 1 ms and wait the rest. This used to
 * be 4000 yields (~60 us) and then usleep(10) forever — on a FIFO task that
 * is a syscall + hrtimer + context switch every ~25 us, ~40k wakeups/s, and
 * it read as 25-30% of a core in rt_time with the emulation doing nothing.
 * Time spent polling at FIFO 20 counts against the per-core RT budget
 * (sched_rt_runtime_us 950000/1000000, NO_RT_RUNTIME_SHARE) exactly like
 * work: measured 2026-09-02, cores 0/1 peaked at 933/869 ms of the 950 ms
 * period next to Move's FIFO 70 audio workers, and when the throttle fired
 * it parked Move's audio thread along with our stage — audible glitches in
 * Move's own output, 60-80 ms stalls of the harness, underruns here.
 * A 250 us poll costs ~1% and the audio ring holds ~136 ms of lead. */
template <class Cond>
static bool shm_wait(jp8000_shm_t *shm, Cond cond) {
    for (int i = 0; i < 200; i++) {
        if (cond()) return true;
        if (shm->child_shutdown) return false;
#ifdef __aarch64__
        __asm__ volatile("yield");
#endif
    }
    useconds_t backoff = 10;
    while (!cond()) {
        if (shm->child_shutdown) return false;
        usleep(backoff);
        backoff = backoff * 2 < 250 ? backoff * 2 : 250;
    }
    return true;
}

/* Push one GRAM handoff into stage `to`'s input ring, waiting for space. */
static void gram_ring_push(jp8000_shm_t *shm, je_stage_t *to, const int32_t *gram) {
    if (!shm_wait(shm, [to]{ return gram_ring_available(to) < JE_GRAM_RING_CAP - 1; }))
        return;
    int wi = to->gram_write & JE_GRAM_RING_MASK;
    for (int k = 0; k < JE_GRAM_COUNT; k++)
        to->gram_ring[wi].gram[k] = gram[k];
    SHM_STORE_FENCE();
    to->gram_write = (to->gram_write + 1) % (JE_GRAM_RING_CAP * 2);
}

/* Parse a comma list of ints; returns the count. */
static int parse_int_list(const char *s, int *out, int max) {
    int n = 0;
    while (*s && n < max) {
        while (*s == ' ' || *s == '\t') s++;
        if (*s < '0' || *s > '9') break;
        out[n++] = atoi(s);
        while (*s && *s != ',' && *s != '\n') s++;
        if (*s == ',') s++;
        else break;
    }
    return n;
}

/* Pipeline shape: defaults, or JE_PIPELINE_FILE ("b1,b2\ncore0,core1,...").
 * Fills shm->num_stages, stage[].lo/hi and cores. Bounds must be ascending
 * in 1..3; anything malformed falls back to the defaults. */
static void configure_pipeline(jp8000_shm_t *shm) {
    int bounds[JE_MAX_STAGES - 1]; int nbounds = 0;
    int cores[JE_MAX_STAGES]; int ncores = 0;

    if (FILE *f = fopen(JE_PIPELINE_FILE, "r")) {
        char line[128];
        if (fgets(line, sizeof(line), f)) nbounds = parse_int_list(line, bounds, JE_MAX_STAGES - 1);
        if (fgets(line, sizeof(line), f)) ncores = parse_int_list(line, cores, JE_MAX_STAGES);
        fclose(f);
        for (int i = 0; i < nbounds; i++)
            if (bounds[i] < 1 || bounds[i] > 3 || (i > 0 && bounds[i] <= bounds[i - 1])) { nbounds = 0; break; }
        for (int i = 0; i < ncores; i++)
            if (cores[i] < 0 || cores[i] > 3) { ncores = 0; break; }
    }
    if (nbounds == 0) {
        for (int i = 0; i < JE_MAX_STAGES - 1 && JE_DEFAULT_BOUNDS[i]; i++) bounds[nbounds++] = JE_DEFAULT_BOUNDS[i];
    }
    for (int i = 0; i < JE_MAX_STAGES; i++)
        shm->cores[i] = (i < ncores) ? cores[i] : JE_DEFAULT_CORES[i];

    shm->num_stages = nbounds + 1;
    shm->stage[0].lo = 0; shm->stage[0].hi = bounds[0];
    for (int s = 1; s < shm->num_stages; s++) {
        shm->stage[s].lo = bounds[s - 1];
        shm->stage[s].hi = (s < nbounds) ? bounds[s] : 4;
    }
}

static void midi_fifo_push(jp8000_shm_t *shm, const uint8_t *msg, int len) {
    if (len < 1 || len > 8) return;
    if (midi_fifo_free(shm) < len + 1) return;
    int wr = shm->midi_write;
    shm->midi_buf[wr] = (uint8_t)len;
    wr = (wr + 1) % MIDI_FIFO_SIZE;
    for (int i = 0; i < len; i++) {
        shm->midi_buf[wr] = msg[i];
        wr = (wr + 1) % MIDI_FIFO_SIZE;
    }
    SHM_STORE_FENCE();
    shm->midi_write = wr;
}

/* =====================================================================
 * Parameters: SysEx ring, DT1 builder, linear images
 *
 * Everything the UI does to the synth is a Roland DT1 into the temp
 * performance area (what the JUCE editor does too, jeController.cpp), and
 * everything it reads comes back as DT1 replies to a data request. The
 * parent never parses a reply: the child copies reply data into linear
 * images in SHM and the parent reads a byte. The functions in this section
 * marked "SPI thread" allocate nothing and never block.
 * ===================================================================== */

static int sx_ring_available(jp8000_shm_t *shm) {
    int avail = shm->sx_write - shm->sx_read;
    if (avail < 0) avail += JP_SX_RING_SIZE;
    return avail;
}

/* SPI thread. Drops the message when the ring is full. */
static bool sx_ring_push(jp8000_shm_t *shm, const uint8_t *msg, int len) {
    if (len < 1 || len > JP_SX_MAX_MSG) return false;
    if (JP_SX_RING_SIZE - 1 - sx_ring_available(shm) < len + 2) return false;
    int wr = shm->sx_write;
    shm->sx_buf[wr] = (uint8_t)(len & 0xff); wr = (wr + 1) % JP_SX_RING_SIZE;
    shm->sx_buf[wr] = (uint8_t)(len >> 8);   wr = (wr + 1) % JP_SX_RING_SIZE;
    for (int i = 0; i < len; i++) {
        shm->sx_buf[wr] = msg[i];
        wr = (wr + 1) % JP_SX_RING_SIZE;
    }
    SHM_STORE_FENCE();
    shm->sx_write = wr;
    return true;
}

/* Child. Returns the length popped into `out`, 0 when empty. */
static int sx_ring_pop(jp8000_shm_t *shm, uint8_t *out, int cap) {
    if (sx_ring_available(shm) < 2) return 0;
    SHM_LOAD_FENCE();
    int rd = shm->sx_read;
    int len = shm->sx_buf[rd]; rd = (rd + 1) % JP_SX_RING_SIZE;
    len |= shm->sx_buf[rd] << 8; rd = (rd + 1) % JP_SX_RING_SIZE;
    for (int i = 0; i < len; i++) {
        uint8_t b = shm->sx_buf[rd];
        if (i < cap) out[i] = b;
        rd = (rd + 1) % JP_SX_RING_SIZE;
    }
    shm->sx_read = rd;
    return len <= cap ? len : 0;
}

/* SPI thread. Builds F0 41 10 00 06 12 a0 a1 a2 a3 data.. cs F7 into `out`
 * (needs n + 12 bytes); returns the length. */
static int dt1_build(uint8_t *out, uint32_t addr, const uint8_t *data, int n) {
    memcpy(out, jpbank::DT1_HEAD, 6);
    out[6] = (addr >> 24) & 0x7f; out[7] = (addr >> 16) & 0x7f;
    out[8] = (addr >> 8) & 0x7f;  out[9] = addr & 0x7f;
    memcpy(out + 10, data, n);
    out[10 + n] = jpbank::checksum(out + 6, 4 + n);
    out[11 + n] = 0xF7;
    return n + 12;
}

/* Where a parameter's bytes live: the image and the temp block. `part`
 * picks the patch for JP_AREA_PATCH keys (0 upper, 1 lower). */
static uint8_t *img_for(jp8000_shm_t *shm, int area, int part, uint32_t *block, int *valid_bit, int *cap) {
    switch (area) {
    case JP_AREA_PATCH:
        *block = part ? JP_TEMP_PATCH_LO : JP_TEMP_PATCH_UP;
        *valid_bit = part ? IMG_PATCH_LO : IMG_PATCH_UP;
        *cap = JP_PATCH_LEN;
        return shm->img_patch[part ? 1 : 0];
    case JP_AREA_PART_UP:
        *block = JP_TEMP_PART_UP; *valid_bit = IMG_PART_UP; *cap = JP_PART_LEN;
        return shm->img_part[0];
    case JP_AREA_PART_LO:
        *block = JP_TEMP_PART_LO; *valid_bit = IMG_PART_LO; *cap = JP_PART_LEN;
        return shm->img_part[1];
    case JP_AREA_SYSTEM:
        /* The system area is not inside the temp performance -- it has its own
         * top-level address (0x00000000), so `block` is 0 here and the writer
         * below picks the base off the area rather than assuming TEMP. The
         * image itself was already being filled from DT1 replies; nothing
         * could address it. */
        *block = 0u; *valid_bit = IMG_SYSTEM; *cap = (int)sizeof(shm->img_system);
        return shm->img_system;
    default:
        *block = JP_TEMP_COMMON; *valid_bit = IMG_COMMON; *cap = JP_COMMON_LEN;
        return shm->img_common;
    }
}

static const jp_param_t *jp_find_param(const char *key) {
    for (int i = 0; i < JP_PARAM_COUNT; i++)
        if (strcmp(jp_params[i].key, key) == 0) return &jp_params[i];
    return nullptr;
}

/* Child. Copy one DT1's data into the images. Replies to the temp request
 * come back as several DT1s that may start at any packed address; the data
 * bytes are consecutive in LINEAR space, so convert the start and walk. */
static void child_image_from_dt1(jp8000_shm_t *shm, const uint8_t *m, int len) {
    if (len < 12 || memcmp(m, jpbank::DT1_HEAD, 6) != 0 || m[len - 1] != 0xF7) return;
    const uint32_t addr = ((uint32_t)m[6] << 24) | ((uint32_t)m[7] << 16) | ((uint32_t)m[8] << 8) | m[9];
    const uint8_t *data = m + 10;
    const int n = len - 12;
    const uint32_t area = addr >> 24;
    uint8_t *img; int cap, bit; uint32_t lin;
    if (area == jpbank::AREA_SYSTEM) {
        if (addr & 0x00ff0000) return;
        img = shm->img_system; cap = (int)sizeof(shm->img_system); bit = IMG_SYSTEM;
        lin = jpbank::packed_to_linear(addr & 0xffff);
    } else if (area == jpbank::AREA_TEMP) {
        const uint32_t local = addr & 0xffff;
        const uint32_t block = local & 0xff00;
        uint32_t ignored;
        /* The offset is relative to the BLOCK BASE, and the blocks are not all
         * spaced the same: common/parts sit 0x100 apart, patches 0x200. A flat
         * `local & 0x1ff` is only right for the patch blocks -- for PART_LO
         * (0x1100) it yields 0x100, past the 7-byte cap, so every reply for the
         * Lower part was silently dropped and IMG_PART_LO never validated. The
         * whole Lower part page read as "unavailable". */
        uint32_t base;
        if (block == JP_TEMP_COMMON)        { img = img_for(shm, JP_AREA_COMMON, 0, &ignored, &bit, &cap); base = JP_TEMP_COMMON; }
        else if (block == JP_TEMP_PART_UP)  { img = img_for(shm, JP_AREA_PART_UP, 0, &ignored, &bit, &cap); base = JP_TEMP_PART_UP; }
        else if (block == JP_TEMP_PART_LO)  { img = img_for(shm, JP_AREA_PART_LO, 0, &ignored, &bit, &cap); base = JP_TEMP_PART_LO; }
        else if ((local & 0xfe00) == JP_TEMP_PATCH_UP) { img = img_for(shm, JP_AREA_PATCH, 0, &ignored, &bit, &cap); base = JP_TEMP_PATCH_UP; }
        else if ((local & 0xfe00) == JP_TEMP_PATCH_LO) { img = img_for(shm, JP_AREA_PATCH, 1, &ignored, &bit, &cap); base = JP_TEMP_PATCH_LO; }
        else return;  /* voice modulator etc. */
        lin = jpbank::packed_to_linear(local - base);
    } else {
        return;
    }
    if (lin >= (uint32_t)cap) return;
    int copy = n;
    if (lin + copy > (uint32_t)cap) copy = cap - (int)lin;
    if (copy <= 0) return;
    memcpy(img + lin, data, copy);
    /* A block counts as valid once its LAST byte has been written: the
     * replies arrive low address first, so this is when it is whole. */
    if (lin + copy >= (uint32_t)cap || bit == IMG_SYSTEM) shm->img_valid |= bit;
    SHM_STORE_FENCE();
    shm->img_seq++;
}


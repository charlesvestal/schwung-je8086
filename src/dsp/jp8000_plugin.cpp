static void* v2_create_instance(const char *module_dir, const char *json_defaults) {
    (void)json_defaults;

    jp8000_instance_t *inst = (jp8000_instance_t*)calloc(1, sizeof(jp8000_instance_t));
    /* The device boots from boot.snap into PERFORM with a performance loaded,
     * so Patch (calloc's 0) was the UI claiming a mode the synth was not in.
     * `mode` only picks which browser is shown -- it is never sent -- so this
     * is purely about telling the truth on entry. */
    if (inst) inst->mode = 1;
    /* MIDI trace, off unless armed by a file (house style: every diagnostic
     * switch off by default). Allocated here, on the control thread. */
    if (inst) {
        inst->trace_on = access("/data/UserData/schwung/jp8000_midi_trace_on", F_OK) == 0
                       || getenv("JP_MIDI_TRACE") != nullptr;
        if (inst->trace_on) {
            inst->trace = (jp8000_instance_t::midi_trace_ev*)
                calloc(jp8000_instance_t::MIDI_TRACE_CAP, sizeof(jp8000_instance_t::midi_trace_ev));
            struct timespec ts; clock_gettime(CLOCK_MONOTONIC, &ts);
            inst->trace_t0 = (uint64_t)ts.tv_sec * 1000000ull + (uint64_t)ts.tv_nsec / 1000ull;
        }
    }
    if (!inst) return nullptr;

    inst->shm = (jp8000_shm_t*)mmap(nullptr, sizeof(jp8000_shm_t),
                                     PROT_READ | PROT_WRITE,
                                     MAP_SHARED | MAP_ANONYMOUS, -1, 0);
    if (inst->shm == MAP_FAILED) {
        free(inst);
        return nullptr;
    }
    memset(inst->shm, 0, sizeof(jp8000_shm_t));
    inst->pipeline_lock_fd = -1;
    /* -1 so the first request for bank 0 is a request */
    inst->shm->patch_bank_cur = -1;
    inst->shm->perf_bank_cur = -1;
    strncpy((char*)inst->shm->module_dir, module_dir, sizeof(inst->shm->module_dir) - 1);

    fprintf(stderr, "JP-8000: creating instance from %s\n", module_dir);
    snprintf((char*)inst->shm->loading_status, sizeof(inst->shm->loading_status), "Initializing...");

    inst->boot_thread_running = 1;
    pthread_create(&inst->boot_thread, nullptr, boot_thread_func, inst);
    return inst;
}

static void v2_destroy_instance(void *instance) {
    jp8000_instance_t *inst = (jp8000_instance_t*)instance;
    if (inst) inst->trace_stop = 1;
    if (!inst) return;
    fprintf(stderr, "JP-8000: destroying\n");

    if (inst->shm) inst->shm->child_shutdown = 1;

    if (inst->boot_thread_running)
        pthread_join(inst->boot_thread, nullptr);

    if (inst->child_pid > 0) {
        kill(inst->child_pid, SIGTERM);
        for (int i = 0; i < 30; i++) {
            int status;
            if (waitpid(inst->child_pid, &status, WNOHANG) == inst->child_pid) break;
            usleep(100000);
        }
        kill(inst->child_pid, SIGKILL);
        waitpid(inst->child_pid, nullptr, 0);
    }

    if (inst->pipeline_lock_fd >= 0) close(inst->pipeline_lock_fd);

    if (inst->shm && inst->shm != MAP_FAILED)
        munmap(inst->shm, sizeof(jp8000_shm_t));

    free(inst);
    fprintf(stderr, "JP-8000: destroyed\n");
}

static void v2_on_midi(void *instance, const uint8_t *msg, int len, int source) {
    jp8000_instance_t *inst = (jp8000_instance_t*)instance;
    if (!inst || !inst->shm || !inst->shm->initialized || len < 1) return;
    (void)source;

    /* SPI callback: no logging here, see vlog(). */
    uint8_t modified[8];
    int n = len > 8 ? 8 : len;
    memcpy(modified, msg, n);

    if (inst->trace_on && inst->trace) {
        struct timespec ts;
        clock_gettime(CLOCK_MONOTONIC, &ts);           /* vDSO, ~340 ns */
        const uint64_t us = (uint64_t)ts.tv_sec * 1000000ull + (uint64_t)ts.tv_nsec / 1000ull;
        jp8000_instance_t::midi_trace_ev &e =
            inst->trace[inst->trace_w % jp8000_instance_t::MIDI_TRACE_CAP];
        e.us = us - inst->trace_t0;
        e.len = (uint8_t)n;
        memcpy(e.b, modified, (size_t)(n > 7 ? 7 : n));
        inst->trace_w++;
    }

    midi_fifo_push(inst->shm, modified, n);
    inst->shm->midi_count++;
}

/* =====================================================================
 * Parameters — parent side. All of this runs on the SPI thread.
 * ===================================================================== */

static int clampi(int v, int lo, int hi) { return v < lo ? lo : v > hi ? hi : v; }

/* raw byte(s) in the image <-> the value the UI sees */
static int jp_raw_to_value(const jp_param_t *p, int raw) { return p->neg ? -raw : raw - p->off; }
static int jp_value_to_raw(const jp_param_t *p, int value) {
    int raw = p->neg ? -value : value + p->off;
    return clampi(raw, 0, p->bit14 ? 16383 : 127);
}

/* Read one parameter. -1 when its image is not valid yet. */
static int param_read(jp8000_instance_t *inst, const jp_param_t *p, int *value) {
    uint32_t block; int bit, cap;
    const int part = (p->area == JP_AREA_PATCH && inst->part == 1) ? 1 : 0;
    const uint8_t *img = img_for(inst->shm, p->area, part, &block, &bit, &cap);
    if (!(inst->shm->img_valid & bit)) return -1;
    if (p->lin + (p->bit14 ? 2 : 1) > cap) return -1;
    SHM_LOAD_FENCE();
    int raw = img[p->lin];
    if (p->bit14) raw = (raw << 7) | img[p->lin + 1];
    *value = jp_raw_to_value(p, raw);
    return 0;
}

/* Write one parameter: image first, then a DT1 to the emulator. A patch
 * key under Edit Part = Both goes to both temp patches. */
static void param_write_block(jp8000_shm_t *shm, const jp_param_t *p, int part, int raw) {
    uint32_t block; int bit, cap;
    uint8_t *img = img_for(shm, p->area, part, &block, &bit, &cap);
    if (p->lin + (p->bit14 ? 2 : 1) > cap) return;
    uint8_t data[2]; int n;
    if (p->bit14) { data[0] = (raw >> 7) & 0x7f; data[1] = raw & 0x7f; n = 2; }
    else { data[0] = raw & 0x7f; n = 1; }
    memcpy(img + p->lin, data, n);
    uint8_t m[16];
    const uint32_t base = (p->area == JP_AREA_SYSTEM) ? JP_ADDR_SYSTEM : JP_ADDR_TEMP;
    const int len = dt1_build(m, base | block | jpbank::linear_to_packed(p->lin), data, n);
    sx_ring_push(shm, m, len);
}

static void param_write(jp8000_instance_t *inst, const jp_param_t *p, int value) {
    const int raw = jp_value_to_raw(p, value);
    if (p->area == JP_AREA_PATCH) {
        if (inst->part == 0 || inst->part == 2) param_write_block(inst->shm, p, 0, raw);
        if (inst->part == 1 || inst->part == 2) param_write_block(inst->shm, p, 1, raw);
    } else {
        param_write_block(inst->shm, p, 0, raw);
    }
}

static void request_load(jp8000_instance_t *inst, int kind) {
    jp8000_shm_t *shm = inst->shm;
    shm->load_kind = kind;
    shm->load_bank = kind ? inst->perf_bank : inst->bank;
    shm->load_index = kind ? inst->performance : inst->patch;
    shm->load_part = inst->part;
    SHM_STORE_FENCE();
    shm->load_seq++;
}

/* `mode` arrives as an index from the hierarchy editor and as a name from
 * everything else. */
static int parse_mode(const char *val) {
    if (strcasecmp(val, "performance") == 0 || strcmp(val, "1") == 0) return 1;
    if (strcasecmp(val, "system") == 0 || strcmp(val, "2") == 0) return 2;
    if (strcasecmp(val, "patch") == 0 || strcmp(val, "0") == 0) return 0;
    return -1;
}

/* ---- state blob -------------------------------------------------------
 * {"mode":0,"part":0,"bank":0,"patch":0,"perf_bank":0,"performance":0,
 *  "temp":"<hex>"} where temp is common(36) partU(7) partL(7) patchU(239)
 * patchL(239) = 528 bytes, i.e. the whole temp performance, so a restore
 * is exact whatever the preset lists look like on the next boot. */

static const uint8_t *state_img(jp8000_shm_t *shm, int i, int *len, uint32_t *block, int *bit) {
    switch (i) {
    case 0: *len = JP_COMMON_LEN; *block = JP_TEMP_COMMON;   *bit = IMG_COMMON;   return shm->img_common;
    case 1: *len = JP_PART_LEN;   *block = JP_TEMP_PART_UP;  *bit = IMG_PART_UP;  return shm->img_part[0];
    case 2: *len = JP_PART_LEN;   *block = JP_TEMP_PART_LO;  *bit = IMG_PART_LO;  return shm->img_part[1];
    case 3: *len = JP_PATCH_LEN;  *block = JP_TEMP_PATCH_UP; *bit = IMG_PATCH_UP; return shm->img_patch[0];
    default:*len = JP_PATCH_LEN;  *block = JP_TEMP_PATCH_LO; *bit = IMG_PATCH_LO; return shm->img_patch[1];
    }
}

static int json_int_field(const char *s, const char *key, int fallback) {
    char pat[32];
    snprintf(pat, sizeof(pat), "\"%s\":", key);
    const char *p = strstr(s, pat);
    if (!p) return fallback;
    p += strlen(pat);
    while (*p == ' ') p++;
    return atoi(p);
}

static int hexval(char c) {
    if (c >= '0' && c <= '9') return c - '0';
    if (c >= 'a' && c <= 'f') return c - 'a' + 10;
    if (c >= 'A' && c <= 'F') return c - 'A' + 10;
    return -1;
}

static int state_get(jp8000_instance_t *inst, char *buf, int buf_len) {
    jp8000_shm_t *shm = inst->shm;
    if (!inst->ui_ready || (shm->img_valid & IMG_ALL_TEMP) != IMG_ALL_TEMP) return -1;
    int n = snprintf(buf, buf_len,
        "{\"version\":2,\"mode\":%d,\"part\":%d,\"bank\":%d,\"patch\":%d,\"perf_bank\":%d,\"performance\":%d,\"temp\":\"",
        inst->mode, inst->part, inst->bank, inst->patch, inst->perf_bank, inst->performance);
    if (n >= buf_len - (JP_TEMP_TOTAL_LEN * 2 + 3)) return -1;
    static const char hexd[] = "0123456789abcdef";
    SHM_LOAD_FENCE();
    for (int i = 0; i < 5; i++) {
        int len; uint32_t block; int bit;
        const uint8_t *img = state_img(shm, i, &len, &block, &bit);
        for (int k = 0; k < len; k++) {
            buf[n++] = hexd[img[k] >> 4];
            buf[n++] = hexd[img[k] & 15];
        }
    }
    buf[n++] = '"';
    /* System settings ride along as their own field, not inside "temp".
     * They are not part of the temp performance -- a patch cannot carry
     * them -- so without this a slot forgets its Remote Ctrl Ch and its
     * master tune on every reload, back to whatever we force at boot.
     *
     * Only the parameters we EXPOSE are stored, one byte each in table
     * order, and restored as individual DT1s. The firmware's own dump of
     * this area starts with PerformanceBank and PerformanceNumber, so
     * replaying it wholesale would also change the loaded performance --
     * a restore that quietly reloads the preset is not a restore. */
    if (shm->img_valid & IMG_SYSTEM) {
        int cnt = 0;
        for (int i = 0; i < JP_PARAM_COUNT; i++)
            if (jp_params[i].area == JP_AREA_SYSTEM) cnt++;
        if (n + cnt * 2 + 12 < buf_len) {
            n += snprintf(buf + n, buf_len - n, ",\"sys\":\"");
            for (int i = 0; i < JP_PARAM_COUNT; i++) {
                if (jp_params[i].area != JP_AREA_SYSTEM) continue;
                const uint8_t b = shm->img_system[jp_params[i].lin];
                buf[n++] = hexd[b >> 4];
                buf[n++] = hexd[b & 15];
            }
            buf[n++] = '"';
        }
    }
    buf[n++] = '}'; buf[n] = 0;
    return n;
}

/* Apply a state blob: UI fields, then the temp image as five DT1s. Called
 * on the SPI thread once ui_ready, and from the boot thread before it. */
static void state_apply(jp8000_instance_t *inst, const char *s) {
    jp8000_shm_t *shm = inst->shm;
    int v;
    if ((v = json_int_field(s, "mode", -1)) >= 0) inst->mode = clampi(v, 0, 2);
    if ((v = json_int_field(s, "part", -1)) >= 0) inst->part = clampi(v, 0, 2);
    if ((v = json_int_field(s, "bank", -1)) >= 0) inst->bank = v;
    if ((v = json_int_field(s, "patch", -1)) >= 0) inst->patch = clampi(v, 0, JP_MAX_PRESETS - 1);
    if ((v = json_int_field(s, "perf_bank", -1)) >= 0) inst->perf_bank = v;
    if ((v = json_int_field(s, "performance", -1)) >= 0) inst->performance = clampi(v, 0, JP_MAX_PRESETS - 1);
    if (shm->patch_bank_count > 0) inst->bank = clampi(inst->bank, 0, shm->patch_bank_count - 1);
    if (shm->perf_bank_count > 0) inst->perf_bank = clampi(inst->perf_bank, 0, shm->perf_bank_count - 1);
    shm->patch_bank_req = inst->bank;
    shm->perf_bank_req = inst->perf_bank;

    /* Before "temp", because a malformed temp block returns early and the
     * system settings are independent of it. */
    const char *sy = strstr(s, "\"sys\":\"");
    if (sy) {
        sy += 7;
        int cnt = 0;
        for (int i = 0; i < JP_PARAM_COUNT; i++)
            if (jp_params[i].area == JP_AREA_SYSTEM) cnt++;
        /* A blob written by a build with a different set of system params
         * is not decodable positionally -- skip it rather than write the
         * wrong byte to the wrong address. */
        int k = 0;
        while (k < cnt * 2 && hexval(sy[k]) >= 0) k++;
        if (k == cnt * 2 && sy[k] == '"') {
            int j = 0;
            for (int i = 0; i < JP_PARAM_COUNT; i++) {
                if (jp_params[i].area != JP_AREA_SYSTEM) continue;
                const int raw = (hexval(sy[j * 2]) << 4) | hexval(sy[j * 2 + 1]);
                j++;
                if (jp_params[i].lin >= (int)sizeof(shm->img_system)) continue;
                shm->img_system[jp_params[i].lin] = (uint8_t)raw;
                uint8_t m[JP_SX_MAX_MSG];
                const uint8_t d = (uint8_t)(raw & 0x7f);
                const int mlen = dt1_build(m, JP_ADDR_SYSTEM | jpbank::linear_to_packed(jp_params[i].lin), &d, 1);
                sx_ring_push(shm, m, mlen);
            }
            shm->img_valid |= IMG_SYSTEM;
        }
    }

    const char *t = strstr(s, "\"temp\":\"");
    if (!t) return;
    t += 8;
    uint8_t temp[JP_TEMP_TOTAL_LEN];
    for (int i = 0; i < JP_TEMP_TOTAL_LEN; i++) {
        const int hi = hexval(t[i * 2]), lo = hi < 0 ? -1 : hexval(t[i * 2 + 1]);
        if (lo < 0) return;   /* short or malformed: leave the synth as it is */
        temp[i] = (uint8_t)((hi << 4) | lo);
    }
    int off = 0;
    for (int i = 0; i < 5; i++) {
        int len; uint32_t block; int bit;
        uint8_t *img = (uint8_t*)state_img(shm, i, &len, &block, &bit);
        memcpy(img, temp + off, len);
        uint8_t m[JP_SX_MAX_MSG];
        const int mlen = dt1_build(m, JP_ADDR_TEMP | block, temp + off, len);
        sx_ring_push(shm, m, mlen);
        shm->img_valid |= bit;
        off += len;
    }
    SHM_STORE_FENCE();
}

/* ---- Bank hierarchy: folder -> bank -> preset -------------------------
 *
 * A real preset library is nested (Charles's is 97 files across 30 folders),
 * and a flat list of 36 labels, each a truncated path, is unreadable on a
 * 128-pixel screen. So the browser walks folders first.
 *
 * The folder is DERIVED from the selected bank rather than stored beside it:
 * one source of truth, so the two cannot drift out of step. Folders are listed
 * in order of first appearance, which keeps "" (the top of banks/, where the
 * factory banks live) first.
 */
struct bank_view {
    int count;
    char (*names)[JP_BANK_NAME_LEN];
    char (*folders)[JP_BANK_NAME_LEN];
    int *sel;                       /* the instance's bank index for this mode */
};

static bank_view bank_view_for(jp8000_instance_t *inst) {
    jp8000_shm_t *shm = inst->shm;
    /* System mode browses nothing: it is a page of settings, not a bank of
     * presets. Reporting count 0 makes every bank_list key
     * answer -1 rather than indexing the patch table by accident. */
    if (inst->mode == 2) return bank_view{0, shm->patch_bank_names, shm->patch_bank_folders, &inst->bank};
    if (inst->mode == 1)
        return bank_view{shm->perf_bank_count, shm->perf_bank_names, shm->perf_bank_folders, &inst->perf_bank};
    return bank_view{shm->patch_bank_count, shm->patch_bank_names, shm->patch_bank_folders, &inst->bank};
}

/* Nth distinct folder, in order of first appearance. Returns nullptr past the
 * end; *out_count (when given) receives the number of distinct folders. */
/* The bank list is FLAT: one row per file, labelled with the file name.
 *
 * A file IS a bank here -- you drop dumps into banks/ and each becomes one --
 * so a folder step was a screen listing directories on the way to a screen
 * listing the files in them, and with everything dropped in at the top it had
 * exactly ONE row on it. Files in sub-folders are still found and still
 * listed; they just do not carry the folder in the label. The only thing that
 * survives from the old scheme is uniquify(), which numbers rows that would
 * otherwise be two identical names -- not to say where a file came from, but
 * so that two rows are never the same row. */
static int bank_label(const bank_view &v, int idx, char *buf, int buf_len) {
    if (idx < 0 || idx >= v.count) return -1;
    return snprintf(buf, buf_len, "%s", v.names[idx]);
}

/* The Nth bank inside `folder`, and how many that folder holds. */
static void v2_set_param(void *instance, const char *key, const char *val) {
    jp8000_instance_t *inst = (jp8000_instance_t*)instance;
    if (!inst || !inst->shm || !key || !val) return;
    jp8000_shm_t *shm = inst->shm;

    if (strcmp(key, "state") == 0) {
        if (inst->ui_ready) { state_apply(inst, val); return; }
        /* Park it for the boot thread. A blob that does not fit is dropped:
         * ours is ~1.2 KB, and a truncated one would half-restore. */
        if (strlen(val) < sizeof(inst->pending_state)) {
            strcpy(inst->pending_state, val);
            inst->pending_state_set = 1;
        }
        return;
    }
    if (!inst->ui_ready) return;

    if (strcmp(key, "mode") == 0) {
        const int m = parse_mode(val);
        if (m >= 0) inst->mode = m;
        return;
    }
    if (strcmp(key, "part") == 0) {
        /* Edit Part IS the hardware's Panel Select (perf-common 0x12). It used
         * to be a UI-only int, so the panel and our selector could disagree
         * about which part an edit addressed. */
        inst->part = clampi(atoi(val), 0, 2);
        const jp_param_t *ps = jp_find_param("panel_select");
        if (ps) param_write(inst, ps, inst->part);
        return;
    }
    if (strcmp(key, "bank_list") == 0) {
        const bank_view v = bank_view_for(inst);
        if (v.count <= 0) return;
        const int target = clampi(atoi(val), 0, v.count - 1);
        *v.sel = target;
        if (inst->mode == 1) { inst->perf_bank = target; shm->perf_bank_req = target; }
        else                 { inst->bank = target;      shm->patch_bank_req = target; }
        return;
    }
    if (strcmp(key, "bank") == 0) {
        inst->bank = clampi(atoi(val), 0, shm->patch_bank_count > 0 ? shm->patch_bank_count - 1 : 0);
        shm->patch_bank_req = inst->bank;
        return;
    }
    if (strcmp(key, "perf_bank") == 0) {
        inst->perf_bank = clampi(atoi(val), 0, shm->perf_bank_count > 0 ? shm->perf_bank_count - 1 : 0);
        shm->perf_bank_req = inst->perf_bank;
        return;
    }
    if (strcmp(key, "patch") == 0) {
        const int n = shm->patch_bank_count > 0 ? shm->patch_bank_sizes[inst->bank] : 0;
        inst->patch = clampi(atoi(val), 0, n > 0 ? n - 1 : 0);
        if (n > 0) request_load(inst, 0);
        return;
    }
    if (strcmp(key, "performance") == 0) {
        const int n = shm->perf_bank_count > 0 ? shm->perf_bank_sizes[inst->perf_bank] : 0;
        inst->performance = clampi(atoi(val), 0, n > 0 ? n - 1 : 0);
        if (n > 0) request_load(inst, 1);
        return;
    }

    const jp_param_t *p = jp_find_param(key);
    if (p) param_write(inst, p, atoi(val));
}

/* chain_params = generated prefix + the two bank enums, whose options are
 * only known once the child has scanned banks/. */
static int chain_params_get(jp8000_shm_t *shm, char *buf, int buf_len) {
    /* Also ungated, for the reason ui_hierarchy is: the metadata is what lets
     * the grid plan a page at all. Only the two bank enums depend on the
     * child's scan, and bank_enum already emits "None" at count 0; the chain
     * host re-reads chain_params on a throttle, so the real bank names land
     * once the scan finishes. */
    int n = snprintf(buf, buf_len, "%s", jp_chain_params_prefix);
    auto bank_enum = [&](const char *key, const char *name, int count, char (*names)[JP_BANK_NAME_LEN]) {
        n += snprintf(buf + n, n < buf_len ? buf_len - n : 0,
                      ",{\"key\":\"%s\",\"name\":\"%s\",\"short_name\":\"Bank\",\"type\":\"enum\",\"options\":[", key, name);
        if (count == 0) n += snprintf(buf + n, n < buf_len ? buf_len - n : 0, "\"None\"");
        for (int i = 0; i < count; i++) {
            /* bank names are file names: escape the two characters JSON minds */
            char esc[JP_BANK_NAME_LEN * 2]; int e = 0;
            for (const char *c = names[i]; *c && e < (int)sizeof(esc) - 2; c++) {
                if (*c == '"' || *c == '\\') esc[e++] = '\\';
                esc[e++] = *c;
            }
            esc[e] = 0;
            n += snprintf(buf + n, n < buf_len ? buf_len - n : 0, "%s\"%s\"", i ? "," : "", esc);
        }
        n += snprintf(buf + n, n < buf_len ? buf_len - n : 0, "],\"default\":0}");
    };
    bank_enum("bank", "Patch Bank", shm->patch_bank_count, shm->patch_bank_names);
    bank_enum("perf_bank", "Perf Bank", shm->perf_bank_count, shm->perf_bank_names);
    n += snprintf(buf + n, n < buf_len ? buf_len - n : 0, "]");
    return n < buf_len ? n : -1;
}

static int v2_get_param(void *instance, const char *key, char *buf, int buf_len) {
    jp8000_instance_t *inst = (jp8000_instance_t*)instance;
    /* -1, not 0: the host's JS bridge builds the string from `buf` and ignores
     * the length we return (schwung_host.c js_host_module_get_param), so a >=0
     * return that leaves `buf` unwritten hands the caller whatever the last
     * call left on that stack slot. Only -1 reads as "no answer". */
    if (!inst || !inst->shm || !key) return -1;
    jp8000_shm_t *shm = inst->shm;

    if (strcmp(key, "__ui") == 0) {
        return snprintf(buf, buf_len, "{\"pages\":[]}");
    }

    if (strcmp(key, "chain_params") == 0) return chain_params_get(shm, buf, buf_len);
    /*
     * UNGATED, exactly as braids serves it (braids_plugin.cpp:801).
     *
     * `jp_ui_hierarchy` is a static string generated from jp8000_params.h --
     * it describes the page STRUCTURE and depends on nothing the child does.
     * Gating it on child_ready cost the shadow UI its whole reason to build
     * pages for the 30-60s the emulator takes to boot: getComponentHierarchy
     * answers null, enterComponentEdit falls through to the bare preset
     * browser, and with no presets yet that is the "No presets" dead end
     * (shadow_ui.js:13332). The values behind these keys are still gated --
     * get_param answers -1 per key until ui_ready -- which is the honest
     * "not yet", and the UI redraws as they arrive.
     */
    if (strcmp(key, "ui_hierarchy") == 0)
        return snprintf(buf, buf_len, "%s", jp_ui_hierarchy);
    if (strcmp(key, "state") == 0) return state_get(inst, buf, buf_len);

    /*
     * THE COMPONENT-ENTRY GATE'S THIRD QUESTION.
     *
     * shared/component_load_gate.mjs decides ENTER / HOLD / FALLBACK when a
     * component editor is opened. An empty ui_hierarchy is ambiguous -- "this
     * module declares none" and "this module has not finished arriving" both
     * read "" -- so the gate asks `<prefix>:is_loading`, and "1" means HOLD:
     * it raises the "Loading..." view and probes again (~0.5s for ~20s, then
     * every 10s) instead of committing, irreversibly, to the bare preset
     * browser. That fallback is the "No presets" dead end; docs/SHADOW_UI.md
     * names Osirus and MiniJV as the reports behind the gate, and jp8000 is
     * the same shape -- create_instance returns in ~20ms having forked, and
     * the emulator is only ready ~4s later.
     *
     * Answered BEFORE the ui_ready gate, and phrased exactly as jv880 phrases
     * it (jv880_plugin.cpp:4141): a load ERROR is not still-loading, or the
     * editor would hold forever on a synth that is never coming up.
     */
    if (strcmp(key, "is_loading") == 0)
        return snprintf(buf, buf_len, "%d",
                        (!shm->loading_complete && !shm->load_error[0]) ? 1 : 0);
    /* The name the editor puts in its header and its announcement; without it
     * enterComponentEditFallback announces the raw component key. */
    if (strcmp(key, "name") == 0) return snprintf(buf, buf_len, "JE-8086");

    if (!inst->ui_ready) {
        /* Not a value yet — a read that cannot be answered is -1, never
         * "0": a default here would plan a page and latch. */
        if (strcmp(key, "__status") != 0) return -1;
    } else {
        if (strcmp(key, "mode") == 0)
            return snprintf(buf, buf_len, "%s",
                            inst->mode == 2 ? "System" : inst->mode ? "Performance" : "Patch");
        if (strcmp(key, "part") == 0) {
            /* Prefer the device's own Panel Select; inst->part is the fallback
             * while the image is still filling. */
            const jp_param_t *ps = jp_find_param("panel_select");
            int v;
            if (ps && param_read(inst, ps, &v) == 0) return snprintf(buf, buf_len, "%d", v);
            return snprintf(buf, buf_len, "%d", inst->part);
        }
        if (strncmp(key, "bank_list", 9) == 0) {
            const bank_view v = bank_view_for(inst);
            if (v.count <= 0) return v.count == 0 ? snprintf(buf, buf_len, "0") : -1;
            const char *rest = key + 9;
            if (!rest[0]) return snprintf(buf, buf_len, "%d", clampi(*v.sel, 0, v.count - 1));
            if (strcmp(rest, "_count") == 0) return snprintf(buf, buf_len, "%d", v.count);
            if (strncmp(rest, "_name", 5) == 0) {
                const char *sfx = rest + 5;
                const int want = sfx[0] == ':' ? atoi(sfx + 1)
                                               : clampi(*v.sel, 0, v.count - 1);
                return bank_label(v, want, buf, buf_len);
            }
            return -1;
        }
        if (strcmp(key, "bank") == 0) return snprintf(buf, buf_len, "%d", inst->bank);
        if (strcmp(key, "perf_bank") == 0) return snprintf(buf, buf_len, "%d", inst->perf_bank);
        if (strcmp(key, "patch") == 0) return snprintf(buf, buf_len, "%d", inst->patch);
        if (strcmp(key, "performance") == 0) return snprintf(buf, buf_len, "%d", inst->performance);
        if (strcmp(key, "__midi_trace") == 0) {
            if (!inst->trace) return snprintf(buf, buf_len, "(not armed)");
            const unsigned w = inst->trace_w;
            const unsigned start = w > (unsigned)jp8000_instance_t::MIDI_TRACE_CAP
                                 ? w - (unsigned)jp8000_instance_t::MIDI_TRACE_CAP : 0;
            int n = snprintf(buf, buf_len, "events=%u\n", w);
            for (unsigned i = start; i < w && n < buf_len - 64; i++) {
                const jp8000_instance_t::midi_trace_ev &e =
                    inst->trace[i % jp8000_instance_t::MIDI_TRACE_CAP];
                n += snprintf(buf + n, buf_len - n, "%9.4f", (double)e.us / 1e6);
                for (int k = 0; k < e.len && k < 7; k++) n += snprintf(buf + n, buf_len - n, " %02X", e.b[k]);
                n += snprintf(buf + n, buf_len - n, "\n");
            }
            return n;
        }
        if (strcmp(key, "banks_skipped") == 0)
            return snprintf(buf, buf_len, "%d", shm->bank_files_skipped);
        /* -1, not a number, while the child is still filling the table for
         * THIS bank. The sizes array still holds the previous bank's answer,
         * and reporting it painted a confident "1/1 Chariots" over a bank of
         * 32 -- a read that has not answered must never become a picture. The
         * `:N` name form already had this guard; the counts beside it did not,
         * so the list drew rows the names then refused to fill. */
        if (strcmp(key, "patch_count") == 0) {
            if (shm->patch_bank_count <= 0) return snprintf(buf, buf_len, "0");
            if (shm->patch_bank_cur != inst->bank) return -1;
            return snprintf(buf, buf_len, "%d", shm->patch_bank_sizes[inst->bank]);
        }
        if (strcmp(key, "performance_count") == 0) {
            if (shm->perf_bank_count <= 0) return snprintf(buf, buf_len, "0");
            if (shm->perf_bank_cur != inst->perf_bank) return -1;
            return snprintf(buf, buf_len, "%d", shm->perf_bank_sizes[inst->perf_bank]);
        }
        /* Name of the current selection, or of `:N` in the current bank.
         * -1 while the child is still filling the table for this bank. */
        if (strncmp(key, "patch_name", 10) == 0 || strncmp(key, "performance_name", 16) == 0) {
            const bool perf = key[0] == 'p' && key[1] == 'e';
            const char *suffix = key + (perf ? 16 : 10);
            int idx = perf ? inst->performance : inst->patch;
            /* Bare `patch_name` / `performance_name` is "what is LOADED", read
             * out of the temp image, and it follows Edit Part. The browser row
             * is not the answer: a factory performance carries its own patches
             * (Chariots' parts read PatchBank = IN PERFORMANCE), so what sounds
             * is "Chariots U", not whatever the patch list happens to be
             * pointing at. The `:N` form stays the browser row name. */
            if (!suffix[0]) {
                uint32_t block; int bit, cap;
                const int rp = (!perf && inst->part == 1) ? 1 : 0;
                const uint8_t *img = img_for(shm, perf ? JP_AREA_COMMON : JP_AREA_PATCH,
                                             rp, &block, &bit, &cap);
                if ((shm->img_valid & bit) && cap >= 16) {
                    SHM_LOAD_FENCE();
                    char nm[17];
                    for (int c = 0; c < 16; c++) {
                        const uint8_t ch = img[c];
                        nm[c] = (ch >= 0x20 && ch < 0x7f) ? (char)ch : ' ';
                    }
                    nm[16] = '\0';
                    int e = 16; while (e > 0 && nm[e - 1] == ' ') e--;
                    nm[e] = '\0';
                    if (e > 0) return snprintf(buf, buf_len, "%s", nm);
                }
                /* image not filled yet -- say so, never invent a name */
                return -1;
            }
            if (suffix[0] == ':') idx = atoi(suffix + 1);
            else return -1;
            if (perf ? (shm->perf_bank_cur != inst->perf_bank) : (shm->patch_bank_cur != inst->bank)) return -1;
            if (idx < 0 || idx >= JP_MAX_PRESETS) return -1;
            SHM_LOAD_FENCE();
            return snprintf(buf, buf_len, "%s", perf ? shm->perf_names[idx] : shm->patch_names[idx]);
        }
        const jp_param_t *p = jp_find_param(key);
        if (p) {
            int v;
            if (param_read(inst, p, &v) < 0) return -1;
            return snprintf(buf, buf_len, "%d", v);
        }
    }

    if (strcmp(key, "__status") == 0) {
        jp8000_shm_t *shm = inst->shm;
        if (shm->load_error[0]) {
            return snprintf(buf, buf_len,
                "{\"status\":\"error\",\"message\":\"%s\"}", shm->load_error);
        }
        if (!shm->loading_complete) {
            return snprintf(buf, buf_len,
                "{\"status\":\"loading\",\"message\":\"%s\"}", shm->loading_status);
        }
        /* Per-stage sample counters, so a stall can be pinned on the stage
         * that stopped rather than read off the ring alone. */
        int n = snprintf(buf, buf_len,
            "{\"status\":\"ready\",\"message\":\"JE-8086 Ready\","
            "\"ring\":%d,\"underruns\":%d,\"midi\":%d,\"peak\":%d,\"min\":%d,\"produced\":[",
            audio_ring_available(shm), shm->underrun_count, shm->midi_count,
            shm->out_peak, shm->out_min);
        for (int s = 0; s < shm->num_stages && n < buf_len; s++)
            n += snprintf(buf + n, buf_len - n, "%s%lld", s ? "," : "",
                          (long long)shm->stage[s].samples_produced);
        if (n < buf_len) n += snprintf(buf + n, buf_len - n, "]}");
        return n;
    }

    return -1;   /* not a key of ours */
}

static int v2_get_error(void *instance, char *buf, int buf_len) {
    jp8000_instance_t *inst = (jp8000_instance_t*)instance;
    if (!inst || !inst->shm) return 0;
    if (inst->shm->load_error[0])
        return snprintf(buf, buf_len, "%s", inst->shm->load_error);
    return 0;
}

static void v2_render_block(void *instance, int16_t *out, int frames) {
    jp8000_instance_t *inst = (jp8000_instance_t*)instance;
    if (!inst || !inst->shm || !inst->shm->child_ready) {
        memset(out, 0, frames * 2 * sizeof(int16_t));
        return;
    }

    jp8000_shm_t *shm = inst->shm;

    /* SPI callback: no logging here, see vlog(). Ring / underrun / per-stage
     * counters are exposed through the __status param instead. */

    /* The audio ring contains samples at 88200 Hz.
     * Output is 44100 Hz. Decimate 2:1 with simple averaging. */
    SHM_LOAD_FENCE();  /* ensure we see audio data written before ring_write */
    int avail = audio_ring_available(shm);
    int needed = frames * 2; /* 2 input samples per 1 output sample */
    int to_read = (avail < needed) ? avail : needed;
    /* Round down to even */
    to_read &= ~1;

    int rd = shm->ring_read;
    int out_idx = 0;
    int peak = 0, mn = 0;
    for (int i = 0; i < to_read; i += 2) {
        if (out_idx >= frames) break;
        /* Average two consecutive samples for 2:1 decimation */
        int32_t l = (int32_t)shm->audio_ring[rd * 2 + 0];
        int32_t r = (int32_t)shm->audio_ring[rd * 2 + 1];
        rd = (rd + 1) % AUDIO_RING_SIZE;
        l += (int32_t)shm->audio_ring[rd * 2 + 0];
        r += (int32_t)shm->audio_ring[rd * 2 + 1];
        rd = (rd + 1) % AUDIO_RING_SIZE;
        l = dc_block(&inst->dc[0], l / 2);
        r = dc_block(&inst->dc[1], r / 2);
        out[out_idx * 2 + 0] = (int16_t)l;
        out[out_idx * 2 + 1] = (int16_t)r;
        /* Block peak / min for __status: the shim only idles a slot whose
         * output stays within +-4 LSB, and the ESP's DAC word carries a small
         * DC pedestal, so "is this slot ever silent" is a question worth
         * being able to answer from the device. */
        int al = l < 0 ? -l : l, ar = r < 0 ? -r : r;
        if (al > peak) peak = al;
        if (ar > peak) peak = ar;
        if (l < mn) mn = l;
        if (r < mn) mn = r;
        out_idx++;
    }
    shm->ring_read = rd;
    shm->out_peak = peak;
    shm->out_min = mn;

    if (out_idx < frames) {
        shm->underrun_count++;
        memset(out + out_idx * 2, 0, (frames - out_idx) * 2 * sizeof(int16_t));
    }
    shm->render_count++;
}


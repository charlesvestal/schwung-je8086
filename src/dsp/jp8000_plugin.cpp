/* Output DC blocker, one per channel. The ESP's DAC word carries a DC
 * pedestal (about -85 in the 24-bit word, -4 LSB after the plugin gain on the
 * left channel, -1 on the right) and the patch's chorus/delay LFOs ride a
 * +-2 LSB ripple on it. The emulation is faithful; the problem is the host:
 * the shim only idles a slot whose output stays within +-4 LSB for a second,
 * so with the pedestal the three stages never sleep and cost ~1.5 cores for
 * the rest of the session even with nothing playing (measured 2026-09-02:
 * 48-52% of a core per stage at rest). A one-pole HPF at ~3 Hz removes the
 * pedestal and is inaudible. */
struct dc_block_t { float x1, y1; };
static inline int16_t dc_block(dc_block_t *d, int32_t x) {
    float y = (float)x - d->x1 + 0.9995f * d->y1;   /* fc ~ 3.5 Hz at 44.1 kHz */
    if (y < 1e-6f && y > -1e-6f) y = 0.0f;           /* no denormal tail */
    d->x1 = (float)x; d->y1 = y;
    int v = (int)lrintf(y);
    if (v > 32767) v = 32767; else if (v < -32768) v = -32768;
    return (int16_t)v;
}

struct jp8000_instance_t {
    jp8000_shm_t *shm;
    pid_t child_pid;
    pthread_t boot_thread;
    volatile int boot_thread_running;
    int pipeline_lock_fd;   /* see JP8000_PIPELINE_LOCK */
    dc_block_t dc[2];

    /* UI state, parent-only. `mode` is a UI fact (which browser is shown);
     * the synth has no such switch. */
    int mode;         /* 0 patch, 1 performance, 2 system */
    int part;         /* 0 upper, 1 lower, 2 both — which patch knob edits address */
    int bank;         /* index into patch banks */
    int patch;        /* index within `bank` */
    int perf_bank;    /* index into performance banks */
    int performance;  /* index within `perf_bank` */

    /* The chain host restores `state` right after create_instance, seconds
     * before the emulator can take a DT1. It is parked here and applied by
     * the boot thread once the child is ready; ui_ready gates every read
     * and edit until then so the grid never plans from an empty image. */
    /* MIDI trace: what the SLOT actually delivers, timestamped. This is the
     * only way to tell Move's sequencer and a note-generating MIDI FX apart
     * from the synth -- jp8000_render bypasses the whole chain path.
     *
     * RT-safe by construction: v2_on_midi runs on the SPI callback, so it only
     * writes into a preallocated ring (no allocation, no I/O, no lock). The
     * dump happens in get_param, off that path. Armed by the file
     * /data/UserData/schwung/jp8000_midi_trace_on, checked once at create. */
    struct midi_trace_ev { uint64_t us; uint8_t len, b[7]; };
    static const int MIDI_TRACE_CAP = 4096;
    midi_trace_ev *trace;
    volatile unsigned trace_w;
    uint64_t trace_t0;
    int trace_on;
    volatile int trace_stop;

    char pending_state[4096];
    volatile int pending_state_set;
    volatile int ui_ready;
};

/*
 * ONE pipeline per device. Three stages at FIFO 20 cost 53-63% of a core
 * each while a chord sounds, on cores 2/1/0; a second pipeline puts 120% of
 * FIFO demand on the same cores, and because equal-priority FIFO tasks do
 * not time-slice and the RT throttle leaves SCHED_OTHER 5% of a core, Move's
 * UI thread, sshd and mDNS stop while the pads (FIFO 70) keep working: an
 * LCD frozen for as long as both pipelines run. Seen twice on 2026-09-02
 * (harness beside a loaded slot). So the emulator process takes an flock on
 * this file for its lifetime — inherited by the stage forks, released when
 * the last of them exits — and a second create_instance, from another slot
 * or from plugin_drive, reports an error instead of booting.
 */
#define JP8000_PIPELINE_LOCK "/data/UserData/schwung/jp8000.pipeline.lock"


